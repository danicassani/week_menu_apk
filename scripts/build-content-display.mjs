// Extract only the small presentation overlay; do not import the full starter
// recipe library into authenticated clients just to hide generic notices.
const recipes = JSON.parse(
  readFileSync("content/starter/recipes.json", "utf8"),
).recipes;
const notes = [],
  steps = [];
const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);
const prefixes = [
  [
    "Prepare the chickpeas from their weighed dry amount using the separate soaking and boiling instructions.",
    "Prepara los garbanzos a partir de su peso en seco siguiendo las instrucciones separadas de remojo y cocción.",
  ],
  [
    "Prepare the dry chickpeas separately.",
    "Prepara aparte los garbanzos secos.",
  ],
  ["Prepare the dry beans separately.", "Prepara aparte las alubias secas."],
  [
    "Soak and vigorously boil the dry kidney beans using their full preparation instructions before using them here.",
    "Remoja y hierve enérgicamente las alubias rojas secas siguiendo todas sus instrucciones de preparación antes de usarlas aquí.",
  ],
  [
    "Prepare dry chickpeas and couscous separately.",
    "Prepara por separado los garbanzos secos y el cuscús.",
  ],
];
for (const recipe of recipes) {
  for (const p of recipe.ingredient_preparation ?? []) {
    const note = {
      ingredient_id: p.ingredient_id,
      instructions: p.instructions,
    };
    if (!notes.some((n) => same(n, note))) notes.push(note);
  }
  for (const component of recipe.components)
    for (const source of component.instructions) {
      let display;
      if (
        source.en ===
        "Cook the weighed dry grain using its preparation instructions; serve with the main dish."
      )
        display = {
          en: "Cook the grain in water according to the packet until tender; serve with the main dish.",
          es: "Cocina el cereal con agua según el envase hasta que esté tierno y sírvelo con el plato principal.",
        };
      const prefix = prefixes.find(
        ([en, es]) => source.en.startsWith(en) && source.es.startsWith(es),
      );
      if (prefix)
        display = {
          en:
            "Soak the pulses for at least 12 hours. Discard the soaking water, rinse and cover with fresh water. Boil vigorously for at least 10 minutes, then cook until fully tender, following any longer packet instructions." +
            (prefix === prefixes[4]
              ? " Prepare couscous according to the packet."
              : "") +
            source.en.slice(prefix[0].length),
          es:
            "Remoja las legumbres al menos 12 horas. Desecha el agua, enjuaga y cubre con agua nueva. Hierve enérgicamente al menos 10 minutos y continúa hasta que estén completamente tiernas, siguiendo el envase si exige más tiempo." +
            (prefix === prefixes[4]
              ? " Prepara el cuscús según el envase."
              : "") +
            source.es.slice(prefix[1].length),
        };
      if (display) {
        let rule = steps.find(
          (r) => same(r.source, source) && same(r.display, display),
        );
        if (!rule) {
          rule = { source, display, targets: [] };
          steps.push(rule);
        }
        rule.targets.push({ recipe_id: recipe.id, component_id: component.id });
      }
    }
}
writeFileSync(
  "content/presentation/recipe-display.json",
  JSON.stringify(
    { recipe_ids: recipes.map((r) => r.id), notes, steps },
    null,
    2,
  ) + "\n",
);
